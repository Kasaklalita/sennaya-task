import { describe, expect, it } from 'vitest';

import { humanizeDates } from '../../web/src/lib/format.js';

/**
 * Перевод дат домена в человеческий вид.
 *
 * Домен печатать ISO-8601 UTC, и это правильно: формат одинаковый везде,
 * тест закрепить его дословно. Но показывать такое человеку нельзя — перевод
 * живёт в интерфейсе, и у него тоже должен быть тест.
 */
describe('humanizeDates', () => {
  it('переписывать дату домена в читаемый вид', () => {
    const result = humanizeDates('Ноутбук продан 2026-01-18T10:00:00.000Z.');

    expect(result).not.toContain('2026-01-18T10:00:00.000Z');
    expect(result).toMatch(/Ноутбук продан .*2026.*\./);
  });

  it('переписывать ВСЕ даты в сообщении, не только первую', () => {
    // Настоящий текст домена про истёкший срок: в нём три метки времени.
    const message =
      'Возврат невозможен: срок возврата истёк. Ноутбук продан 2026-09-19T10:31:17.202Z, ' +
      'вернуть его можно было не позднее 2026-10-03T10:31:17.202Z включительно, ' +
      'сейчас 2026-10-09T10:31:17.202Z.';

    const result = humanizeDates(message);

    expect(result).not.toMatch(/\d{4}-\d{2}-\d{2}T/);
    expect(result).toContain('Возврат невозможен: срок возврата истёк.');
    expect(result).toContain('включительно');
  });

  it('год оставлять: без него дата путать', () => {
    expect(humanizeDates('2026-01-18T10:00:00.000Z')).toContain('2026');
  });

  it('текст без дат не трогать', () => {
    const message = 'Ноутбук уже в статусе «Бронь»: переход в тот же статус не предусмотрен.';

    expect(humanizeDates(message)).toBe(message);
  });

  it('не ломаться на том, что похоже на дату, но датой не является', () => {
    // Февраль, 30-е число — такой даты нет. Текст должен уцелеть, а не стать «Invalid Date».
    const result = humanizeDates('метка 2026-02-30T99:99:99.999Z конец');

    expect(result).toContain('конец');
    expect(result).not.toContain('Invalid');
  });
});
