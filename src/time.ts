/**
 * Работа со временем.
 *
 * Вынесено отдельно, потому что этим пользуются все слои домена: и конструктор
 * агрегата, и условия на рёбрах, и сам движок.
 */

export const MS_IN_DAY = 24 * 60 * 60 * 1000;

/**
 * Проверяет, что перед нами именно живая дата.
 *
 * Принимает `unknown`, а не `Date`, намеренно: на границе системы (JSON из запроса,
 * строка из БД) в поле типа `Date` вполне может оказаться строка — типы в рантайме
 * не существуют. `new Date('не дата')` тоже валиден по типу, но содержит `NaN`.
 */
export function isValidDate(value: unknown): value is Date {
  return value instanceof Date && !Number.isNaN(value.getTime());
}

/**
 * Копия даты.
 *
 * `Date` мутабелен, а `Object.freeze` его не закрывает: время лежит во внутреннем
 * слоте, а не в свойстве. Поэтому неизменяемость журнала держится именно на
 * копировании — на входе и при записи, — и копий в коде много. Названная функция
 * объясняет, зачем они, лучше чем шесть повторений `new Date(x.getTime())`.
 */
export function copyDate(date: Date): Date {
  return new Date(date.getTime());
}
